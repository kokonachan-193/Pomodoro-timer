class I18n:
    def __init__(self, path: Path):
        self.path = path
        self.lang = "ja"
        self.load()

    def load(self) -> None:
        try:
            if self.path.exists():
                data = json.loads(self.path.read_text(encoding="utf-8"))
                lang = str(data.get("lang", "ja")).lower()
                if lang in ("ja", "jp", "japanese"):
                    self.lang = "ja"
                elif lang in ("en", "english"):
                    self.lang = "en"
        except Exception:
            self.lang = "ja"

    def save(self) -> None:
        try:
            self.path.parent.mkdir(parents=True, exist_ok=True)
            payload = {}
            if self.path.exists():
                try:
                    payload = json.loads(self.path.read_text(encoding="utf-8"))
                except Exception:
                    payload = {}
            payload["lang"] = self.lang
            self.path.write_text(json.dumps(payload, ensure_ascii=False, indent=2), encoding="utf-8")
        except Exception:
            pass

    def set_lang(self, lang: str) -> None:
        self.lang = "en" if str(lang).lower().startswith("en") else "ja"
        self.save()

    def t(self, key: str, **kwargs) -> str:
        table = STRINGS.get(self.lang) or STRINGS["ja"]
        text = table.get(key) or STRINGS["ja"].get(key) or key
        if kwargs:
            try:
                return text.format(**kwargs)
            except Exception:
                return text
        return text
